export type DashboardDictionary = (typeof dictionary)["en"];

export const BASE_DASHBOARD_DICTIONARY: DashboardDictionary = dictionary.en;

export function getDashboardDictionary(language: string): DashboardDictionary {
  const key = language as SupportedDashboardLanguage;
  return dictionary[key] || dictionary.en;
}

export function mergeDashboardDictionary(
  partial: Record<string, string> | undefined,
  language: string,
): DashboardDictionary {
  return {
    ...getDashboardDictionary(language),
    ...(partial || {}),
  };
}
